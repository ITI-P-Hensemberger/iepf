// Purpose: Write the frontend's API types from this app's OpenAPI document.
// CI regenerates them and fails if the committed file differs.
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'

import app from '@/app'
import { closeDb } from '@/db'
import { openApiConfig } from '@/lib/configure-open-api'

const OUTPUT = path.resolve(import.meta.dirname, '../../../frontend/lib/api/schema.ts')

const HEADER = `// Generated by apps/backend/src/scripts/generate-api-types.ts from the backend OpenAPI document.
// Do not edit: run \`pnpm --filter iepf-backend run api:types\` after changing a backend route.
/* eslint-disable */
`

const document = app.getOpenAPIDocument(openApiConfig)
const ast = await openapiTS(document as Parameters<typeof openapiTS>[0])
await writeFile(OUTPUT, HEADER + astToString(ast))
await closeDb()
